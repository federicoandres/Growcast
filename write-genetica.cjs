const fs = require('fs')

const lines = []
lines.push("interface Intervencion {")
lines.push("  tipo: 'trasplante' | 'poda' | 'producto' | 'cosecha'")
lines.push("  fecha: string")
lines.push("  detalle: string")
lines.push("}")
lines.push("")
lines.push("interface Props {")
lines.push("  descripcion: string")
lines.push("  cantidadPlantas: number")
lines.push("  fechaInicio: string")
lines.push("  intervenciones: readonly Intervencion[]")
lines.push("  onNuevaIntervencion?: () => void")
lines.push("}")
lines.push("")
lines.push("const tipoLabel: Record<Intervencion['tipo'], string> = {")
lines.push("  trasplante: 'Trasplante',")
lines.push("  poda: 'Poda',")
lines.push("  producto: 'Producto aplicado',")
lines.push("  cosecha: 'Cosecha',")
lines.push("}")
lines.push("")
lines.push("function calcularSemanaDia(fechaInicio: string) {")
lines.push("  const inicio = new Date(fechaInicio)")
lines.push("  const ahora = new Date()")
lines.push("  const diffMs = ahora.getTime() - inicio.getTime()")
lines.push("  const diffDias = Math.floor(diffMs / (1000 * 60 * 60 * 24))")
lines.push("  const semana = Math.floor(diffDias / 7) + 1")
lines.push("  const dia = (diffDias % 7) + 1")
lines.push("  return { semana, dia }")
lines.push("}")
lines.push("")
lines.push("function ultimaPorTipo(intervenciones: readonly Intervencion[], tipo: string) {")
lines.push("  const filtradas = intervenciones.filter((i) => i.tipo === tipo)")
lines.push("  if (filtradas.length === 0) return null")
lines.push("  return filtradas.reduce((a, b) => (new Date(a.fecha) > new Date(b.fecha) ? a : b))")
lines.push("}")
lines.push("")
lines.push("export function GeneticaCard(props: Props) {")
lines.push("  const descripcion = props.descripcion")
lines.push("  const cantidadPlantas = props.cantidadPlantas")
lines.push("  const fechaInicio = props.fechaInicio")
lines.push("  const intervenciones = props.intervenciones")
lines.push("  const onNuevaIntervencion = props.onNuevaIntervencion")
lines.push("  const { semana, dia } = calcularSemanaDia(fechaInicio)")
lines.push("  const tipos: Intervencion['tipo'][] = ['trasplante', 'poda', 'producto', 'cosecha']")
lines.push("")
lines.push("  return (")
lines.push("    <div className='bg-gray-900 border border-gray-800 rounded-2xl p-6 mb-6'>")
lines.push("      <div className='flex justify-between items-start mb-4 border-b border-gray-800 pb-3'>")
lines.push("        <div>")
lines.push("          <h2 className='text-lg font-bold text-green-400'>{descripcion}</h2>")
lines.push("          <p className='text-gray-500 text-xs mt-1'>{cantidadPlantas} plantas</p>")
lines.push("        </div>")
lines.push("        <span data-testid='semana-dia' className='text-xs px-3 py-1 rounded-full bg-gray-800 text-gray-300'>")
lines.push("          Semana {semana} - Dia {dia}")
lines.push("        </span>")
lines.push("      </div>")
lines.push("")
lines.push("      <p className='text-gray-400 text-xs mb-2'>Ultimas intervenciones</p>")
lines.push("      <div className='grid grid-cols-2 gap-3 md:grid-cols-4 mb-4'>")
lines.push("        {tipos.map((tipo) => {")
lines.push("          const ultima = ultimaPorTipo(intervenciones, tipo)")
lines.push("          return (")
lines.push("            <div key={tipo} className='bg-gray-800 rounded-xl p-3'>")
lines.push("              <p className='text-gray-500 text-xs mb-1'>{tipoLabel[tipo]}</p>")
lines.push("              {ultima ? (")
lines.push("                <div>")
lines.push("                  <p className='text-sm text-white'>{ultima.detalle}</p>")
lines.push("                  <p className='text-gray-600 text-xs mt-1'>{ultima.fecha}</p>")
lines.push("                </div>")
lines.push("              ) : (")
lines.push("                <p className='text-gray-600 text-xs'>Sin registro</p>")
lines.push("              )}")
lines.push("            </div>")
lines.push("          )")
lines.push("        })}")
lines.push("      </div>")
lines.push("")
lines.push("      <button")
lines.push("        data-testid='boton-nueva-intervencion'")
lines.push("        onClick={onNuevaIntervencion}")
lines.push("        className='text-sm px-4 py-1.5 rounded bg-green-700 hover:bg-green-600 text-white'")
lines.push("      >")
lines.push("        + Registrar intervencion")
lines.push("      </button>")
lines.push("    </div>")
lines.push("  )")
lines.push("}")

const code = lines.join('\n')
fs.writeFileSync('src/components/GeneticaCard.tsx', code, { encoding: 'utf8' })
console.log('OK - GeneticaCard escrito, ' + lines.length + ' lineas')