const fs = require('fs')

const lines = []
lines.push("interface Genetica {")
lines.push("  id: string")
lines.push("  nombre: string")
lines.push("}")
lines.push("")
lines.push("interface DatosCultivo {")
lines.push("  nombre: string")
lines.push("  etapa: string")
lines.push("  fechaInicio: string")
lines.push("  cantidadPlantas: number")
lines.push("  geneticaId: string")
lines.push("}")
lines.push("")
lines.push("interface Props {")
lines.push("  geneticasDisponibles: readonly Genetica[]")
lines.push("  onGuardar: (datos: DatosCultivo) => void")
lines.push("  onCargarGenetica: () => void")
lines.push("}")
lines.push("")
lines.push("import { useState } from 'react'")
lines.push("")
lines.push("export function NuevoCultivoForm({ geneticasDisponibles, onGuardar, onCargarGenetica }: Props) {")
lines.push("  const [nombre, setNombre] = useState('')")
lines.push("  const [etapa, setEtapa] = useState('clones')")
lines.push("  const [fechaInicio, setFechaInicio] = useState('')")
lines.push("  const [cantidadPlantas, setCantidadPlantas] = useState('')")
lines.push("  const [geneticaId, setGeneticaId] = useState(geneticasDisponibles[0]?.id ?? '')")
lines.push("")
lines.push("  function handleGuardar() {")
lines.push("    onGuardar({")
lines.push("      nombre,")
lines.push("      etapa,")
lines.push("      fechaInicio,")
lines.push("      cantidadPlantas: Number(cantidadPlantas),")
lines.push("      geneticaId,")
lines.push("    })")
lines.push("  }")
lines.push("")
lines.push("  return (")
lines.push("    <div className='max-w-md mx-auto bg-gray-900 rounded-xl p-6 space-y-4'>")
lines.push("      <h2 className='text-xl font-bold text-green-400'>Nuevo cultivo</h2>")
lines.push("")
lines.push("      <div>")
lines.push("        <label htmlFor='nombre' className='block text-sm text-gray-400 mb-1'>Nombre</label>")
lines.push("        <input")
lines.push("          id='nombre'")
lines.push("          value={nombre}")
lines.push("          onChange={(e) => setNombre(e.target.value)}")
lines.push("          className='w-full bg-gray-800 rounded px-3 py-2 text-white'")
lines.push("        />")
lines.push("      </div>")
lines.push("")
lines.push("      <div>")
lines.push("        <label htmlFor='etapa' className='block text-sm text-gray-400 mb-1'>Etapa</label>")
lines.push("        <select")
lines.push("          id='etapa'")
lines.push("          value={etapa}")
lines.push("          onChange={(e) => setEtapa(e.target.value)}")
lines.push("          className='w-full bg-gray-800 rounded px-3 py-2 text-white'")
lines.push("        >")
lines.push("          <option value='clones'>Clones</option>")
lines.push("          <option value='vegetativo'>Vegetativo</option>")
lines.push("          <option value='floracion'>Floracion</option>")
lines.push("          <option value='floracion_tardia'>Floracion tardia</option>")
lines.push("        </select>")
lines.push("      </div>")
lines.push("")
lines.push("      <div>")
lines.push("        <label htmlFor='fecha-inicio' className='block text-sm text-gray-400 mb-1'>Fecha de inicio</label>")
lines.push("        <input")
lines.push("          id='fecha-inicio'")
lines.push("          type='date'")
lines.push("          value={fechaInicio}")
lines.push("          onChange={(e) => setFechaInicio(e.target.value)}")
lines.push("          className='w-full bg-gray-800 rounded px-3 py-2 text-white'")
lines.push("        />")
lines.push("      </div>")
lines.push("")
lines.push("      <div>")
lines.push("        <label htmlFor='cantidad-plantas' className='block text-sm text-gray-400 mb-1'>Cantidad de plantas</label>")
lines.push("        <input")
lines.push("          id='cantidad-plantas'")
lines.push("          type='number'")
lines.push("          value={cantidadPlantas}")
lines.push("          onChange={(e) => setCantidadPlantas(e.target.value)}")
lines.push("          className='w-full bg-gray-800 rounded px-3 py-2 text-white'")
lines.push("        />")
lines.push("      </div>")
lines.push("")
lines.push("      {geneticasDisponibles.length === 0 ? (")
lines.push("        <div className='bg-yellow-950 border border-yellow-700 rounded p-3 space-y-2'>")
lines.push("          <p className='text-yellow-400 text-sm'>Tenes que cargar una genetica primero</p>")
lines.push("          <button")
lines.push("            data-testid='boton-cargar-genetica'")
lines.push("            onClick={onCargarGenetica}")
lines.push("            className='bg-yellow-600 hover:bg-yellow-700 text-white px-3 py-1.5 rounded text-sm'")
lines.push("          >")
lines.push("            Cargar genetica")
lines.push("          </button>")
lines.push("        </div>")
lines.push("      ) : (")
lines.push("        <div>")
lines.push("          <label htmlFor='genetica' className='block text-sm text-gray-400 mb-1'>Genetica</label>")
lines.push("          <select")
lines.push("            id='genetica'")
lines.push("            value={geneticaId}")
lines.push("            onChange={(e) => setGeneticaId(e.target.value)}")
lines.push("            className='w-full bg-gray-800 rounded px-3 py-2 text-white'")
lines.push("          >")
lines.push("            {geneticasDisponibles.map((g) => (")
lines.push("              <option key={g.id} value={g.id}>{g.nombre}</option>")
lines.push("            ))}")
lines.push("          </select>")
lines.push("        </div>")
lines.push("      )}")
lines.push("")
lines.push("      <button")
lines.push("        data-testid='boton-guardar-cultivo'")
lines.push("        onClick={handleGuardar}")
lines.push("        className='w-full bg-green-600 hover:bg-green-700 text-white py-2 rounded font-medium'")
lines.push("      >")
lines.push("        Guardar")
lines.push("      </button>")
lines.push("    </div>")
lines.push("  )")
lines.push("}")

const code = lines.join('\n')
fs.writeFileSync('src/components/NuevoCultivoForm.tsx', code, { encoding: 'utf8' })
console.log('OK - NuevoCultivoForm.tsx escrito, ' + lines.length + ' lineas')